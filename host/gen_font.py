#!/usr/bin/env python3
"""Bake Pillow's built-in bitmap font into a C header for the host harness
(device builds use the Flipper's own fonts via the canvas)."""
import sys
from PIL import Image, ImageDraw, ImageFont

font = ImageFont.load_default_imagefont()
asc, desc = font.getmetrics() if hasattr(font, "getmetrics") else (9, 2)
height = 11
glyphs = []
for code in range(32, 127):
    ch = chr(code)
    l, t, r, b = font.getbbox(ch)
    w = max(r, 1) + 1
    img = Image.new("1", (w, height), 0)
    ImageDraw.Draw(img).text((0, 0), ch, font=font, fill=1)
    rows = []
    for y in range(height):
        bits = 0
        for x in range(w):
            if img.getpixel((x, y)):
                bits |= 1 << x
        rows.append(bits)
    glyphs.append((w, rows))

out = [f"/* Generated by host/gen_font.py */", f"#define HOST_FONT_H {height}",
       "static const struct { unsigned char w; unsigned short rows[%d]; } host_font[95] = {" % height]
for w, rows in glyphs:
    out.append("    {%d, {%s}}," % (w, ", ".join(str(r) for r in rows)))
out.append("};")
open(sys.argv[1], "w").write("\n".join(out) + "\n")
