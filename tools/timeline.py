MUSIC0_RESUME = 14  # sync-table order where music0 resumes for U2E


def music0_order(o):
    """Sync-table music0 order -> order index in Future Crew's MUSIC0.S3M
    (which keeps the first-half stop patterns/end marker and a skip)."""
    return o if o < 14 else (o + 4 if o <= 22 else o + 5)


def music1_order(o, orders):
    """Sync-table music1 order -> index in MUSIC1.S3M (skip markers kept)."""
    n = -1
    for i, p in enumerate(orders):
        if p != fcmusic.SKIP:
            n += 1
            if n == o:
                return i
    raise ValueError(o)


def main():
    fc = sys.argv[1]
    out = sys.argv[2] if len(sys.argv) > 2 else os.path.join(
        os.path.dirname(os.path.abspath(__file__)), "..", "src", "timeline.h")
    m0 = fcmusic.parse(fcmusic.unscramble(open(os.path.join(fc, "MAIN/MUSIC0.S3M"), "rb").read()))
    m1 = fcmusic.parse(fcmusic.unscramble(open(os.path.join(fc, "MAIN/MUSIC1.S3M"), "rb").read()))

    # music0 runs at tempo 120 (STARTMUS.C patches the module's tempo byte)
    t0a = fcmusic.row_times(m0, 0, tempo=0x78)
    t0b = fcmusic.row_times(m0, music0_order(MUSIC0_RESUME), tempo=0x78)
    t1 = fcmusic.row_times(m1, 0)

    lines = [
        "#pragma once",
        "",
        "/* Generated by tools/timeline.py from the original music - do not edit.",
        " * SYNC_* are milliseconds from the start of the music segment they",
        " * belong to (see SEG_*): music0 first half, music1, music0 second half. */",
        "",
        "#define SEG_S0A 0",
        "#define SEG_S1  1",
        "#define SEG_S0B 2",
        "",
    ]
    for name, (song, o, r) in SYNCS.items():
        if song == 0:
            fo = music0_order(o)
            seg = "S0B" if o >= MUSIC0_RESUME else "S0A"
            table = t0b if o >= MUSIC0_RESUME else t0a
        else:
            fo, seg, table = music1_order(o, m1["orders"]), "S1", t1
        # a sync fires once playback reaches or passes its position
        hit = [t for (po, pr), t in table.items() if (po, pr) >= (fo, r)]
        if not hit:
            sys.exit("sync %s (%d,%d) never reached" % (name, o, r))
        lines.append("#define SYNC_%-24s %6d /* %s order %d row %d */" % (name, round(min(hit)), seg, o, r))
    os.makedirs(os.path.dirname(os.path.abspath(out)), exist_ok=True)
    open(out, "w").write("\n".join(lines) + "\n")
    print("wrote", out)


if __name__ == "__main__":
    main()
