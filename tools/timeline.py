#!/usr/bin/env python3
"""Generate src/timeline.h: music sync points in milliseconds and the Play
All schedule.

    python3 tools/timeline.py /path/to/SecondReality [out.h]

Times come from simulating Future Crew's own (unscrambled) modules. The
sync positions are the (order, row) points where the demo's parts change,
as recovered from the original demo's sync table (orders are counted
without skip/end markers; music0's are mapped onto Future Crew's file,
whose order list has extra stop/skip entries).

The demo plays three music segments:
  S0A  music0 from the start, until it stops during the title picture
  S1   music1 from the start (begins when the title picture ends)
  S0B  music0 resumed at its second half (1.8 s after the JP logo ends)
"""
