#!/usr/bin/env python3
"""Generate src/gfx/sintab.c: 1024-entry sine table in Q14."""
import math
import sys

N = 1024
vals = [round(math.sin(2 * math.pi * i / N) * 16384) for i in range(N)]
vals = [max(-16384, min(16384, v)) for v in vals]
out = ["/* Generated by tools/gen_sintab.py - do not edit. */",
       '#include "gfx.h"', "", "const int16_t sin_lut[FX_ANGLE_STEPS] = {"]
for i in range(0, N, 12):
    out.append("    " + ", ".join(str(v) for v in vals[i:i + 12]) + ",")
out.append("};")
path = sys.argv[1] if len(sys.argv) > 1 else "src/gfx/sintab.c"
with open(path, "w") as f:
    f.write("\n".join(out) + "\n")
